def main() -> None:
    ap = argparse.ArgumentParser(description="Build the natural-language query regime")
    ap.add_argument("--data-dir", type=str, default="../data")
    ap.add_argument("--source", type=str, default="queries_short.json")
    ap.add_argument("--out", type=str, default="queries_natural.json")
    args = ap.parse_args()

    data = Path(args.data_dir)
    src = json.loads((data / "eval" / args.source).read_text(encoding="utf-8"))
    if isinstance(src, dict):
        src = src.get("queries", [])
    by_qid = {q["qid"]: q for q in src}

    out = []
    missing = []
    for qid, text in NATURAL_QUERIES.items():
        base = by_qid.get(qid)
        if base is None:
            missing.append(qid)
            continue
        out.append({"qid": qid, "text": text, "year": base.get("year"),
                    "split": base.get("split"), "style": "natural"})

    (data / "eval" / args.out).write_text(json.dumps(out, indent=1, ensure_ascii=False),
                                          encoding="utf-8")

    words = [len(q["text"].split()) for q in out]
    rep = Report("build_natural_queries", data, args)
    rep.section("Natural-language query regime")
    rep.stat("queries_written", len(out))
    rep.stat("qids_not_found_in_source", len(missing))
    rep.stat("mean_words", round(sum(words) / len(words), 1) if words else 0)
    rep.stat("min_words", min(words) if words else 0)
    rep.stat("max_words", max(words) if words else 0)
    rep.stat("splits", json.dumps({s: sum(1 for q in out if q["split"] == s)
                                   for s in {q["split"] for q in out}}))
    rep.note("Model-authored (Claude), not written by a practising lawyer and not "
             "generated by the pipeline's own model. Disclose as such: these test whether "
             "the system survives a question phrased the way a user would phrase it, not "
             "whether it matches real user query logs.")
    rep.note("qids are preserved from the source regime, so the citation-derived qrels "
             "apply unchanged and results remain comparable across regimes.")
    rep.save()
    print(f"[ok] wrote {len(out)} queries -> {data / 'eval' / args.out}")
    if missing:
        print(f"[warn] {len(missing)} qids not in source: {missing[:5]}")


if __name__ == "__main__":
    main()
