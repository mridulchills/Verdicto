"""
Build the `natural` query regime: lawyer-style questions instead of judgment spans.

Why this regime exists
----------------------
Every other regime (keyword / short / medium / long) is a verbatim span lifted out of
the judgment being used as the query case. Those spans share vocabulary, spelling and
even OCR artefacts with the corpus, which flatters the lexical channel in a way no real
user query does: a practising lawyer types a question, not a paragraph of the judgment
they have not read yet.

The qid is preserved, so the citation-derived qrels apply unchanged and results stay
directly comparable to the other regimes. Only the query TEXT differs.

Provenance: these 30 questions were written by Claude (Anthropic) from each case's
title and issues text, not by a practising lawyer and not generated by the pipeline's
own model. That is a limitation to disclose — they are model-authored, human-reviewed
in structure but not validated by a legal professional.

Usage (from Backend/):
    python -m scripts.eval.build_natural_queries --data-dir ../data
"""
